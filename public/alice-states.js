export const totalDeFrasesAlice = estadosAlice.reduce(
  (total, estado) => total + estado.frases.length,
  0
);

export function buscarEstadoAlice(idOuNomeDaImagem) {
  return estadosAlice.find(
    ({ id, imagem }) => id === idOuNomeDaImagem || imagem === idOuNomeDaImagem
  ) ?? null;
}

export function escolherFalaAlice(idOuNomeDaImagem, indiceAnterior = -1) {
  const estado = buscarEstadoAlice(idOuNomeDaImagem);

  if (!estado) {
    return null;
  }

  const opcoes = estado.frases
    .map((frase, indice) => ({ frase, indice }))
    .filter(({ indice }) => indice !== indiceAnterior);

  const escolha = opcoes[Math.floor(Math.random() * opcoes.length)];

  return {
    imagem: estado.imagem,
    estado: estado.estado,
    tom: estado.tom,
    frase: escolha.frase,
    indiceDaFrase: escolha.indice
  };
}
